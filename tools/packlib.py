#!/usr/bin/env python3
"""Packs the lists in tools/lib (standard-library symbols) into src/stdsym_data.inc.

Each list is text, one entry per line:
    #Name[:Base]     starts a class (or module) section; "#" alone is the global section
    name(params)>ret a function or method; params and >ret are optional
    name:Type        a property or constant
The text is compressed with the tiny LZ77 that stdsym.c decodes:
    4 bytes  little-endian size of the text
    then ops: c < 128  -> c + 1 literal bytes follow
              c >= 128 -> copy (c & 127) + 4 bytes from 'offset' back; offset is 2 bytes little-endian
Usage: tools/packlib.py            (from the repository root)
"""
import os
import sys

IDS = ["php", "c", "cpp", "py", "js", "go", "rust", "java"]


def compress(data):
    out = bytearray(len(data).to_bytes(4, "little"))
    n = len(data)
    table = {}
    lit = bytearray()

    def flush():
        i = 0
        while i < len(lit):
            chunk = lit[i:i + 128]
            out.append(len(chunk) - 1)
            out.extend(chunk)
            i += 128
        lit.clear()

    i = 0
    while i < n:
        best_len, best_off = 0, 0
        if i + 4 <= n:
            key = bytes(data[i:i + 4])
            for j in reversed(table.get(key, [])[-48:]):
                off = i - j
                if off > 65535:
                    break
                l = 4
                while l < 131 and i + l < n and data[j + l] == data[i + l]:
                    l += 1
                if l > best_len:
                    best_len, best_off = l, off
        if best_len >= 4:
            flush()
            out.append(0x80 | (best_len - 4))
            out.extend(best_off.to_bytes(2, "little"))
            for k in range(i, min(i + best_len, n - 3)):
                table.setdefault(bytes(data[k:k + 4]), []).append(k)
            i += best_len
        else:
            lit.append(data[i])
            if i + 4 <= n:
                table.setdefault(bytes(data[i:i + 4]), []).append(i)
            i += 1
    flush()
    return bytes(out)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    lines = ["/* Generated by tools/packlib.py from the lists in tools/lib. Do not edit. */\n"]
    total_raw = total_z = 0
    for ident in IDS:
        path = os.path.join(here, "lib", ident + ".txt")
        data = open(path, "rb").read() if os.path.exists(path) else b""
        data = b"\n".join(l.rstrip() for l in data.split(b"\n") if l.strip() and not l.startswith(b"//")) + b"\n"
        z = compress(data)
        total_raw += len(data)
        total_z += len(z)
        lines.append("static const unsigned char std_%s[] = {\n" % ident)
        for i in range(0, len(z), 24):
            lines.append("    " + ",".join(str(b) for b in z[i:i + 24]) + ",\n")
        lines.append("};\n")
        print("%-4s %7d -> %6d bytes" % (ident, len(data), len(z)), file=sys.stderr)
    print("total %7d -> %6d bytes" % (total_raw, total_z), file=sys.stderr)
    open(os.path.join(root, "src", "stdsym_data.inc"), "w").write("".join(lines))


if __name__ == "__main__":
    main()
